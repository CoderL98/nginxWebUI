function initial() {
  if (!browser) return 'zh';
  const saved = localStorage.getItem('nginxwebui-lang');
  return saved === 'en' ? 'en' : 'zh';
}

export const lang = writable(initial());

lang.subscribe((value) => {
  if (browser) {
    localStorage.setItem('nginxwebui-lang', value);
    document.documentElement.lang = value === 'en' ? 'en' : 'zh-CN';
  }
});

export function toggleLang() {
  lang.update((value) => (value === 'en' ? 'zh' : 'en'));
}

/** t('save') → the word in the chosen language. */
export function t(key) {
  let current = 'zh';
  lang.subscribe((value) => (current = value))();
  const table = words[current] || words.zh;
  return table[key] ?? words.zh[key] ?? key;
}

/** Reactive version: put $tt in markup. */
export const tt = {
  subscribe(run) {
    return lang.subscribe((value) => run((key) => (words[value] || words.zh)[key] ?? key));
  }
};
